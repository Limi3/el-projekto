#!/usr/bin/env python3
"""Bundle B's pure Luau modules + specs into one script runnable by the plain `luau` CLI.

Roblox modules use `require(script.Parent.X)`. The CLI has no Instance tree, so this builds a
tiny fake tree mirroring preview-b.project.json and wraps every module as a function(script).
Only modules that avoid Roblox APIs can run this way; that is intentional: game logic that matters
for correctness is kept pure so it can be tested here, outside Studio.

Usage: python3 tests/b/tools/bundle.py > /tmp/bundle.luau && luau /tmp/bundle.luau
"""
import os, re, sys, json

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))

# virtual roots (name -> directory), mirroring where Rojo places them in the preview project
TREE = {
    "Content": "src/shared/content",
    "World": "src/server/world",
    "Client": "src/client",
    "TestsB": "tests/b",
}

nodes = []  # (id, name, parent_id, path or None)

def add_dir(name, path, parent):
    nid = len(nodes)
    init = None
    for cand in ("init.luau", "init.lua"):
        if os.path.exists(os.path.join(path, cand)):
            init = os.path.join(path, cand)
    nodes.append((nid, name, parent, init))
    for entry in sorted(os.listdir(path)):
        full = os.path.join(path, entry)
        if entry.startswith(".") or entry in ("init.luau", "init.lua"):
            continue
        if os.path.isdir(full):
            add_dir(entry, full, nid)
        elif entry.endswith(".luau") or entry.endswith(".lua"):
            base = re.sub(r"\.(server|client)?\.?luau?$", "", entry)
            base = re.sub(r"\.(server|client)$", "", base)
            cid = len(nodes)
            nodes.append((cid, base, nid, full))
    return nid

root_id = len(nodes)
nodes.append((root_id, "Root", None, None))
for name, rel in TREE.items():
    p = os.path.join(ROOT, rel)
    if os.path.isdir(p):
        add_dir(name, p, root_id)

def strip(src):
    # `export type` is only legal at top level; inside the wrapper function plain `type` works.
    src = re.sub(r"^(\s*)export type ", r"\1type ", src, flags=re.M)
    src = re.sub(r"^--!strict\s*$", "", src, flags=re.M)
    src = re.sub(r"^--!nonstrict\s*$", "", src, flags=re.M)
    return src

out = []
out.append("""-- AUTO-GENERATED by tests/b/tools/bundle.py; do not edit
if warn == nil then warn = function(...) print("WARN", ...) end end
local __src = {}
local __nodes = {}
local __cache = {}
local __loading = {}
local NodeMT = {}
NodeMT.__index = function(self, key)
    local m = rawget(NodeMT, key)
    if m then return m end
    local kids = rawget(self, "__kids")
    if kids and kids[key] then return kids[key] end
    error("fake Instance '" .. rawget(self, "Name") .. "' has no child '" .. tostring(key) .. "'", 2)
end
function NodeMT.FindFirstChild(self, name) return rawget(self, "__kids")[name] end
function NodeMT.WaitForChild(self, name) return NodeMT.__index(self, name) end
function NodeMT.GetChildren(self) local t = {} for _, c in rawget(self, "__kids") do table.insert(t, c) end return t end
NodeMT.__tostring = function(self) return rawget(self, "Name") end
local function __mk(id, name, parent)
    local n = setmetatable({ Name = name, __id = id, __kids = {} }, NodeMT)
    __nodes[id] = n
    if parent ~= nil then
        rawset(n, "Parent", __nodes[parent])
        rawget(__nodes[parent], "__kids")[name] = n
    end
    return n
end
local __realrequire = require
function require(target)
    if type(target) == "table" and rawget(target, "__id") ~= nil then
        local id = rawget(target, "__id")
        if __cache[id] ~= nil then return __cache[id] end
        if __loading[id] then error("cyclic require of " .. rawget(target, "Name")) end
        local f = __src[id]
        if not f then error("no module source for " .. rawget(target, "Name")) end
        __loading[id] = true
        local v = f(target)
        __loading[id] = nil
        __cache[id] = v
        return v
    end
    return __realrequire(target)
end
""")
for nid, name, parent, path in nodes:
    out.append("__mk(%d, %s, %s)" % (nid, json.dumps(name), "nil" if parent is None else str(parent)))
for nid, name, parent, path in nodes:
    if path:
        with open(path, encoding="utf-8") as fh:
            src = strip(fh.read())
        rel = os.path.relpath(path, ROOT)
        out.append("__src[%d] = function(script) -- %s\n%s\nend" % (nid, rel, src))

entry = sys.argv[1] if len(sys.argv) > 1 else "TestsB/unit/run"
parts = entry.split("/")
out.append("local __n = __nodes[%d]" % root_id)
for p in parts:
    out.append("__n = __n[%s]" % json.dumps(p))
out.append("return require(__n)")
print("\n".join(out))
